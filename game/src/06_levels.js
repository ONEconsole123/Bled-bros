function assembleLevel(def) {
  if (def.boss) return ARENAS[def.arena].slice();
  const rows = Array.from({ length: ROWS }, () => '');
  for (const name of def.chunks) {
    const ch = CHUNKS[name];
    if (!ch) throw new Error('chunk inconnu: ' + name);
    const w = ch[0].length;
    for (const r of ch) if (r.length !== w) throw new Error('chunk ' + name + ' largeur incoherente');
    const pad = ROWS - ch.length;
    for (let r = 0; r < ROWS; r++) rows[r] += r < pad ? '.'.repeat(w) : ch[r - pad];
  }
  return rows;
}
