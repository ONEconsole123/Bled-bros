// Concatenates game/src/*.js into a single self-contained HTML file,
// then exports it as a JS string module for the Expo WebView.
// Usage: node game/build.js
const fs = require('fs');
const path = require('path');

const root = __dirname;
const srcDir = path.join(root, 'src');
const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
const code = files.map((f) => `// ---- ${f} ----\n` + fs.readFileSync(path.join(srcDir, f), 'utf8')).join('\n');
const tpl = fs.readFileSync(path.join(root, 'template.html'), 'utf8');
const html = tpl.replace('/*__GAME__*/', () => '(function(){\n' + code + '\n})();');

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'index.html'), html);

const out = path.join(root, '..', 'src', 'gameHtml.js');
fs.writeFileSync(
  out,
  '// AUTO-GENERATED by game/build.js — do not edit by hand.\n' +
    'export default ' + JSON.stringify(html) + ';\n'
);
console.log(`built ${files.length} modules -> game/dist/index.html (${(html.length / 1024).toFixed(1)} KB) + src/gameHtml.js`);
