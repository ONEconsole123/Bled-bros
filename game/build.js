// Builds the game from game/src/*.js into two outputs:
//   1. src/gameHtml.js  — the page as a JS string, loaded by the Expo app's WebView
//   2. web/             — the public website (PWA: manifest, icons, offline service worker)
// Also writes game/dist/index.html for quick local testing.
// Usage: node game/build.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = __dirname;
const repo = path.join(root, '..');
const srcDir = path.join(root, 'src');
const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
const code = files.map((f) => `// ---- ${f} ----\n` + fs.readFileSync(path.join(srcDir, f), 'utf8')).join('\n');
const tpl = fs.readFileSync(path.join(root, 'template.html'), 'utf8');
const page = (head, webScript) =>
  tpl
    .replace('<!--__HEAD__-->', () => head)
    .replace('<!--__WEB_SCRIPT__-->', () => webScript)
    .replace('/*__GAME__*/', () => '(function(){\n' + code + '\n})();');

// ---------- app + local test ----------
const appHtml = page('', '');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'index.html'), appHtml);
fs.writeFileSync(
  path.join(repo, 'src', 'gameHtml.js'),
  '// AUTO-GENERATED by game/build.js — do not edit by hand.\n' + 'export default ' + JSON.stringify(appHtml) + ';\n'
);

// ---------- website ----------
// Absolute URL for link previews (WhatsApp, X, Facebook need it). On Vercel the production
// domain is provided at build time; SITE_URL overrides it (custom domain).
const host = process.env.SITE_URL || (process.env.VERCEL_PROJECT_PRODUCTION_URL ? 'https://' + process.env.VERCEL_PROJECT_PRODUCTION_URL : '');
const abs = (p) => (host ? host.replace(/\/$/, '') + '/' + p : p);
const title = 'Bled Bros — les chasseurs de ghwal';
const desc = 'Jeu de plateforme 16-bit 100 % marocain : 4 héros, 12 niveaux de Fès à Marrakech, et les ghouls, sorcières et djinns des contes de grand-mère. Gratuit, dans le navigateur.';
const head = [
  `<meta name="description" content="${desc}">`,
  '<link rel="manifest" href="manifest.webmanifest">',
  '<link rel="icon" type="image/png" href="favicon.png">',
  '<link rel="apple-touch-icon" href="apple-touch-icon.png">',
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-title" content="Bled Bros">',
  '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
  '<meta property="og:type" content="website">',
  `<meta property="og:title" content="${title}">`,
  `<meta property="og:description" content="${desc}">`,
  `<meta property="og:image" content="${abs('og-image.png')}">`,
  '<meta property="og:image:width" content="1200">',
  '<meta property="og:image:height" content="630">',
  '<meta property="og:locale" content="fr_FR">',
  host ? `<meta property="og:url" content="${host}">` : '',
  '<meta name="twitter:card" content="summary_large_image">',
  `<meta name="twitter:title" content="${title}">`,
  `<meta name="twitter:description" content="${desc}">`,
  `<meta name="twitter:image" content="${abs('og-image.png')}">`,
].filter(Boolean).join('\n');
const webScript = `<script>
if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost')) {
  addEventListener('load', function () { navigator.serviceWorker.register('sw.js').catch(function () {}); });
}
</script>`;
const webHtml = page(head, webScript);

const webDir = path.join(repo, 'web');
fs.rmSync(webDir, { recursive: true, force: true });
fs.mkdirSync(webDir, { recursive: true });
fs.writeFileSync(path.join(webDir, 'index.html'), webHtml);

const staticDir = path.join(root, 'web-static');
const statics = fs.readdirSync(staticDir);
for (const f of statics) fs.copyFileSync(path.join(staticDir, f), path.join(webDir, f));

fs.writeFileSync(
  path.join(webDir, 'manifest.webmanifest'),
  JSON.stringify(
    {
      name: 'Bled Bros',
      short_name: 'Bled Bros',
      description: desc,
      lang: 'fr',
      start_url: './',
      scope: './',
      display: 'fullscreen',
      orientation: 'landscape',
      background_color: '#120a14',
      theme_color: '#120a14',
      categories: ['games', 'entertainment'],
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2
  )
);

// Service worker: the page is fetched network-first (new versions arrive right away),
// everything is cached so the game also works offline once visited.
const version = crypto.createHash('sha1').update(webHtml).digest('hex').slice(0, 10);
const precache = ['./', 'manifest.webmanifest', ...statics.filter((f) => f !== 'og-image.png')];
fs.writeFileSync(
  path.join(webDir, 'sw.js'),
  `// AUTO-GENERATED by game/build.js
const CACHE = 'bledbros-${version}';
const ASSETS = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./'))
    );
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`
);

console.log(
  `built ${files.length} modules -> src/gameHtml.js (app, ${(appHtml.length / 1024).toFixed(1)} KB) + web/ (site, ${statics.length + 3} files${host ? ', ' + host : ''})`
);
